//! Prints the snapshot layout and the shared constants as TypeScript
//! (`web/src/sim/abi.gen.ts`).

use requiem_sim::abi::{snap, ABI_VERSION};
use requiem_sim::crowd::Draw;
use requiem_sim::mage::{show, STAFF_BUTT, STAFF_HEAD};
use requiem_sim::fx::{self, kind as fxk, Fx, LIFE, LIGHTS};
use requiem_sim::knight::{self, clip, CLIPS, FRAMES};
use requiem_sim::moves::{mv, MOVES};
use requiem_sim::sim::{act, btn, ev, tune, Bolt, BOLTS};
use requiem_sim::skel::{bone, figure, BONES, PARENT};

fn main() {
    println!("// Generated by `cargo run -p requiem-sim --bin abi`. Do not edit.");
    println!("export const ABI_VERSION = {ABI_VERSION};");
    println!("export const SNAP_LEN = {};", snap::LEN);
    println!("export const SNAP = {{");
    for (name, at, _) in snap::FIELDS {
        println!("  {name}: {at},");
    }
    println!("}} as const;");
    println!("export const BONES = {BONES};");
    println!("export const BONE_PARENT = {PARENT:?} as const;");
    println!("export const LIGHTS = {LIGHTS};");
    println!("export const DRAW_BYTES = {};", core::mem::size_of::<Draw>());
    println!("export const FX_BYTES = {};", core::mem::size_of::<Fx>());
    println!("export const FX_SLOTS = {};", fx::SLOTS);
    println!("export const BOLT_BYTES = {};", core::mem::size_of::<Bolt>());
    println!("export const BOLTS = {BOLTS};");
    println!("export const STAFF_HEAD = {STAFF_HEAD};");
    println!("export const STAFF_BUTT = {STAFF_BUTT};");
    println!("export const KNIGHT_FRAMES = {FRAMES};");
    println!("export const KNIGHT_CLIPS = [");
    for (i, c) in CLIPS.iter().enumerate() {
        println!("  {{ first: {}, frames: {}, len: {}, looped: {} }},", knight::first(i as u8), c.frames, c.len, c.looped);
    }
    println!("] as const;");
    println!("export const FX_LIFE = {LIFE:?} as const;");
    println!("export const MOVES = [");
    for m in MOVES.iter() {
        println!("  {{ name: {:?}, len: {}, cancel: {} }},", m.name, m.len, m.cancel);
    }
    println!("] as const;");
    macro_rules! table {
        ($title:literal, $($m:ident :: $k:ident),* $(,)?) => {
            println!("export const {} = {{", $title);
            $( println!("  {}: {},", stringify!($k), $m::$k); )*
            println!("}} as const;");
        };
    }
    table!("BTN", btn::LIGHT, btn::HEAVY, btn::EVADE, btn::UNSEAL, btn::GUARD, btn::HOVER, btn::RESET);
    table!(
        "EV", ev::SWING, ev::HIT, ev::KILL, ev::HEAVY_HIT, ev::CIRCLE, ev::BEAM, ev::LIGHTNING, ev::FIRE, ev::BOLT, ev::BURST, ev::EVADE, ev::BLOCK, ev::HURT, ev::GATHER, ev::UNSEAL, ev::FALLEN, ev::REVIVE, ev::WON,
        ev::READY, ev::PILLAR
    );
    table!("ACT", act::FREE, act::MOVE, act::GUARD, act::HIT, act::DOWN);
    table!("SHOW", show::FREE, show::MOVE, show::GUARD, show::HIT, show::DOWN);
    table!("MV", mv::NONE, mv::L1, mv::L2, mv::L3, mv::L4, mv::L5, mv::BEAM, mv::RISE, mv::LIGHTNING, mv::HELLFIRE, mv::BARRAGE, mv::EVADE, mv::UNSEAL);
    table!("CLIP", clip::IDLE, clip::WALK, clip::RUN, clip::CHOP, clip::SWEEP, clip::STAGGER, clip::KNOCK, clip::AIR, clip::DOWN, clip::RISE, clip::COLLAPSE);
    table!("FIGURE", figure::MAGE, figure::KNIGHT_SWORD, figure::KNIGHT_HALBERD, figure::KNIGHT_GREAT, figure::DEMON);
    table!(
        "FX", fxk::NONE, fxk::ARC, fxk::SPARK, fxk::SHOCK, fxk::WHIRL, fxk::CIRCLE, fxk::CONE, fxk::BURST, fxk::BEAM, fxk::PILLAR, fxk::LIGHTNING, fxk::JOLT, fxk::HELLFIRE, fxk::EMBER, fxk::VOLLEY, fxk::BLINK, fxk::GATHER,
        fxk::UNSEAL, fxk::SOUL, fxk::DUST, fxk::GUARD, fxk::BLOCK, fxk::SLASH, fxk::HURT, fxk::MUZZLE
    );
    table!(
        "BONE", bone::PELVIS, bone::SPINE, bone::CHEST, bone::NECK, bone::HEAD, bone::CLAV_L, bone::ARM_UL, bone::ARM_LL, bone::HAND_L, bone::CLAV_R, bone::ARM_UR, bone::ARM_LR, bone::HAND_R, bone::LEG_UL,
        bone::LEG_LL, bone::FOOT_L, bone::LEG_UR, bone::LEG_LR, bone::FOOT_R, bone::SKIRT_L, bone::SKIRT_R, bone::TAIL_L0, bone::TAIL_L1, bone::TAIL_L2, bone::TAIL_R0, bone::TAIL_R1, bone::TAIL_R2, bone::PROP
    );
    table!("TUNE", tune::RUN_SPEED, tune::HOVER_SPEED, tune::HP_MAX, tune::MANA_MAX);
}
